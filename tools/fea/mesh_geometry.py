"""Gmsh 메시 도구(PRD Z절 FR-FEA-03): STEP/STL → 사면체(C3D4/C3D10) CalculiX .inp.

시뮬레이터(Sim.Core.Fea.GmshMesher)가 외부 프로세스로 호출한다 — Gmsh 를 링크하지 않는다.

  python tools/fea/mesh_geometry.py <in.step|in.stl> --out mesh.inp --size 0.005 [--order 2] [--summary out.json] [--body N]
  python tools/fea/mesh_geometry.py <in.step> --list-bodies bodies.json   (솔리드별 부피·경계 상자만)

- STEP: OpenCASCADE 로 읽고(단위 m 로 변환), 바디가 여럿이면 fragment 로 접촉면을 공유(결합, bonded)시킨다.
  --body N: 가져온 순서 N 번째(1부터) 솔리드 하나만 남겨 메시(조립 STEP 에서 부품 하나 — Fusion 내보내기는 바디 이름이 비어 있어
  massprops parts 순서와 같은 번호를 쓴다; 요약에 그 바디 부피·경계 상자를 남겨 호출자가 부피로 대조한다).
- STL: 표면 분류(classifySurfaces) → 기하 재구성(createGeometry) → 체적. 닫힌 껍질이 여럿이면(조립체)
  결합 정보를 알 수 없으므로 종료 코드 3 으로 알린다 → 호출자가 STEP 을 쓰거나 복셀 대체 메셔로 간다.
- 출력 .inp 는 *NODE + *ELEMENT(TYPE=C3D10|C3D4) 만. 절점 순서는 Abaqus(Gmsh 10절점 사면체의 마지막 두 절점 교환).

종료 코드: 0 성공, 2 입력 오류, 3 STL 다중 껍질, 4 메시 실패.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import struct
import sys

EXIT_OK, EXIT_INPUT, EXIT_MULTI, EXIT_MESH = 0, 2, 3, 4

# Gmsh 10절점 사면체 → Abaqus C3D10: 모서리 (3,2) 와 (3,1) 위치가 서로 바뀌어 있다.
GMSH_TET10_TO_ABAQUS = [0, 1, 2, 3, 4, 5, 6, 7, 9, 8]


def read_stl(path):
    """STL(바이너리/ASCII) → 삼각형 목록 [((x,y,z),(x,y,z),(x,y,z)), ...]."""
    with open(path, "rb") as f:
        data = f.read()
    tris = []
    if len(data) >= 84:
        n = struct.unpack_from("<I", data, 80)[0]
        if 84 + n * 50 == len(data):
            for i in range(n):
                v = struct.unpack_from("<12f", data, 84 + i * 50)
                tris.append((tuple(v[3:6]), tuple(v[6:9]), tuple(v[9:12])))
            return tris
    verts = []
    for line in data.decode("ascii", errors="replace").splitlines():
        s = line.strip().split()
        if s and s[0].lower() == "vertex":
            verts.append(tuple(float(x) for x in s[1:4]))
    if not verts or len(verts) % 3:
        raise ValueError(f"STL 을 읽을 수 없습니다: {path}")
    return [tuple(verts[i:i + 3]) for i in range(0, len(verts), 3)]


def connected_components(tris, tol=1e-9):
    """정점을 공유하는 삼각형 묶음(닫힌 껍질 후보) → 삼각형 인덱스 목록들."""
    key = {}
    parent = list(range(len(tris)))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for i, t in enumerate(tris):
        for p in t:
            k = tuple(round(c / tol) for c in p)
            if k in key:
                a, b = find(i), find(key[k])
                if a != b:
                    parent[a] = b
            else:
                key[k] = i
    groups = {}
    for i in range(len(tris)):
        groups.setdefault(find(i), []).append(i)
    return sorted(groups.values(), key=len, reverse=True)


def write_inp(path, nodes, elems, etype):
    """nodes: [(x,y,z)] (번호 = 인덱스+1), elems: [[절점 인덱스 0 기반]]."""
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("** generated by tools/fea/mesh_geometry.py (Gmsh)\n*NODE\n")
        for i, (x, y, z) in enumerate(nodes):
            f.write(f"{i + 1}, {x:.12g}, {y:.12g}, {z:.12g}\n")
        f.write(f"*ELEMENT, TYPE={etype}\n")
        for e, conn in enumerate(elems):
            f.write(f"{e + 1}, " + ", ".join(str(n + 1) for n in conn) + "\n")


def tet_volume(a, b, c, d):
    ux, uy, uz = (b[i] - a[i] for i in range(3))
    vx, vy, vz = (c[i] - a[i] for i in range(3))
    wx, wy, wz = (d[i] - a[i] for i in range(3))
    return (ux * (vy * wz - vz * wy) - uy * (vx * wz - vz * wx) + uz * (vx * wy - vy * wx)) / 6.0


def mesh_file(path, size, order=2, threads=1, body=None):
    """메시 생성 → (nodes, elems, etype, info). 실패 시 예외(MeshError)."""
    import gmsh  # 지연 import — 도움말·단위 함수는 gmsh 없이 동작

    ext = os.path.splitext(path)[1].lower()
    if ext not in (".step", ".stp", ".stl"):
        raise InputError(f"지원하지 않는 형식: {ext} (STEP/STL)")
    if not os.path.isfile(path):
        raise InputError(f"파일이 없습니다: {path}")
    if not (size > 0):
        raise InputError("--size 는 양수여야 합니다")
    info = {"input": os.path.abspath(path), "size_m": size, "order": order}
    if body is not None:
        if ext == ".stl":
            raise InputError("--body 는 STEP 에서만 쓸 수 있습니다")
        if body < 1:
            raise InputError("--body 는 1 이상이어야 합니다")
        info["body"] = body
    if ext == ".stl":
        comps = connected_components(read_stl(path))
        info["shells"] = len(comps)
        if len(comps) > 1:
            raise MultiShellError(f"STL 에 닫힌 껍질이 {len(comps)}개 — 결합 정보가 없어 STEP 이 필요합니다(또는 복셀 대체)")
    # 재시도(STEP 만 — STL 은 분류된 표면 메시가 곧 형상이라 한 번만). 실모델 센서 STEP(2026-10-07):
    # 몸체가 면 878개·최소 면 0.0007 mm² 의 정밀 형상이라 4 mm 요소에서는 표면 메시가 서로 뚫려 Delaunay 는
    # "PLC Error: segment and facet intersect", Frontal 은 빈 체적, HXT 는 실패 — 2 mm 에서 성공.
    # 같은 세션에서 mesh.clear() 후 재시도하면 실패 상태가 남아 모든 체적이 비었다 → 시도마다 세션을 새로 연다.
    attempts = [(size, 1)] if ext == ".stl" else [(s, a) for s in (size, size / 2, size / 4) for a in (1, 4)]
    last_err = None
    for h, algo in attempts:
        try:
            return _mesh_once(gmsh, path, ext, h, algo, order, threads, dict(info), body)
        except (InputError, MultiShellError):
            raise
        except MeshError as ex:
            last_err = ex
    raise last_err


def _mesh_once(gmsh, path, ext, h, algo, order, threads, info, body=None):
    # 시도마다 세션을 새로 여는데, 기본 initialize 는 세션마다 SIGINT 처리기를 설치 · 해제하고 사용자 gmshrc 를 읽는다.
    # 한 프로세스에서 initialize/finalize 를 되풀이하면(재시도 · pytest) 드물게 네이티브 접근 위반(0xC0000005)으로 죽었다(2026-10-11)
    # → 처리기 설치 없이(interruptible=False — 앱은 취소 때 프로세스를 끝냄), 설정 파일 없이(결과가 사용자 설정에 좌우되지 않게).
    gmsh.initialize(["-nt", str(max(1, threads))] if threads else [], readConfigFiles=False, interruptible=False)
    try:
        gmsh.option.setNumber("General.Terminal", 0)
        gmsh.model.add("mns")
        if ext == ".stl":
            gmsh.merge(path)
            gmsh.model.mesh.removeDuplicateNodes()
            gmsh.model.mesh.classifySurfaces(40 * math.pi / 180, True, True, math.pi)
            gmsh.model.mesh.createGeometry()
            surfs = [s[1] for s in gmsh.model.getEntities(2)]
            loop = gmsh.model.geo.addSurfaceLoop(surfs)
            gmsh.model.geo.addVolume([loop])
            gmsh.model.geo.synchronize()
        else:
            gmsh.option.setString("Geometry.OCCTargetUnit", "M")
            gmsh.model.occ.importShapes(path)
            gmsh.model.occ.synchronize()
            vols = gmsh.model.getEntities(3)
            if not vols:
                raise MeshError("STEP 에 솔리드(체적)가 없습니다")
            if body is not None:
                if body > len(vols):
                    raise InputError(f"--body {body}: STEP 솔리드는 {len(vols)}개입니다")
                keep = vols[body - 1]
                gmsh.model.occ.remove([d for d in vols if d != keep], recursive=True)
                gmsh.model.occ.synchronize()
                vols = [keep]
                info["bodyVolume_m3"] = gmsh.model.occ.getMass(*keep)
                info["bodyBBox_m"] = list(gmsh.model.occ.getBoundingBox(*keep))
            if len(vols) > 1:
                # 부품 간섭 제거: 큰 부품부터 남기고 작은 부품에서 겹친 부분을 잘라 낸 뒤 fragment 로 접촉면을 결합한다.
                # 실모델 센서는 몸체–날개 0.2 mm, 스파이크–몸체 0.1 cm³ 간섭이 있어, fragment 만 하면 얇은 겹침 조각이,
                # 전체 fuse 하면 합친 면이 표면 메시 교차(PLC Error)를 일으켜 몸체 체적에 요소가 생기지 않았다(2026-10-07).
                # 맞닿기만 한 부품은 잘라 낼 것이 없어 결과가 같다.
                vol_in = sum(gmsh.model.occ.getMass(3, t) for _, t in vols)
                order_v = sorted(vols, key=lambda d: -gmsh.model.occ.getMass(*d))
                kept = [order_v[0]]
                for d in order_v[1:]:
                    out, _ = gmsh.model.occ.cut([d], kept, removeObject=True, removeTool=False)
                    kept += out
                gmsh.model.occ.synchronize()
                cut_vols = gmsh.model.getEntities(3)
                overlap = vol_in - sum(gmsh.model.occ.getMass(3, t) for _, t in cut_vols)
                if overlap > 1e-12:
                    info["overlapVolume_m3"] = overlap
                    info["overlapsResolved"] = "작은 부품에서 큰 부품과 겹친 부분 제거"
                gmsh.model.occ.fragment(cut_vols[:1], cut_vols[1:])
                gmsh.model.occ.synchronize()
            info["volumes"] = len(gmsh.model.getEntities(3))
        gmsh.option.setNumber("Mesh.Optimize", 1)
        gmsh.option.setNumber("Mesh.MeshSizeMax", h)
        gmsh.option.setNumber("Mesh.MeshSizeMin", h * 0.1)
        gmsh.option.setNumber("Mesh.Algorithm3D", algo)
        gmsh.model.mesh.generate(3)
        # Delaunay 는 PLC 오류를 예외 없이 로그만 남기고 그 체적을 비워 둘 때가 있다 → 체적마다 요소 수 확인
        empty = [t for _, t in gmsh.model.getEntities(3)
                 if not any(len(e) for e in gmsh.model.mesh.getElements(3, t)[1])]
        if empty:
            raise MeshError(f"요소 {h * 1000:g} mm · 3D 알고리즘 {algo}: 요소 없는 체적 {empty}")
        info["algorithm3d"] = algo
        info["size_used_m"] = h
        if order == 2:
            gmsh.option.setNumber("Mesh.SecondOrderLinear", 0)
            gmsh.model.mesh.setOrder(2)
        tags, coords, _ = gmsh.model.mesh.getNodes()
        index = {int(t): i for i, t in enumerate(tags)}
        etype_gmsh = 11 if order == 2 else 4
        types, _, node_tags = gmsh.model.mesh.getElements(3)
        elems = []
        for t, nt in zip(types, node_tags):
            if t != etype_gmsh:
                continue
            k = 10 if order == 2 else 4
            for e in range(len(nt) // k):
                conn = [index[int(x)] for x in nt[e * k:(e + 1) * k]]
                if k == 10:
                    conn = [conn[j] for j in GMSH_TET10_TO_ABAQUS]
                elems.append(conn)
        if not elems:
            raise MeshError("사면체 요소가 만들어지지 않았습니다(닫힌 표면인지 확인)")
        # 쓰인 절점만 압축 번호
        used = sorted({n for c in elems for n in c})
        remap = {n: i for i, n in enumerate(used)}
        nodes = [tuple(coords[3 * n:3 * n + 3]) for n in used]
        elems = [[remap[n] for n in c] for c in elems]
        vol = 0.0
        for c in elems:
            v = tet_volume(*(nodes[n] for n in c[:4]))
            if v <= 0:
                raise MeshError("음의 부피 요소 — 표면 방향이 뒤집혔거나 자기 교차")
            vol += v
        info.update(nodes=len(nodes), elements=len(elems), volume_m3=vol)
        return nodes, elems, ("C3D10" if order == 2 else "C3D4"), info
    except (InputError, MultiShellError, MeshError):
        raise
    except Exception as ex:  # gmsh 내부 오류 → 메시 실패
        raise MeshError(f"Gmsh 실패: {ex}") from ex
    finally:
        gmsh.finalize()


def list_bodies(path):
    """STEP 솔리드 목록(가져온 순서, 1부터): 부피·겉넓이·경계 상자 — 메시 전에 massprops 부피로 대조하고 메시 크기를 정할 때 쓴다
    (겉넓이 A 는 두께 추정 t ≈ 2V/A — 얇은 판·관에서 벽 두께)."""
    import gmsh

    gmsh.initialize([], readConfigFiles=False, interruptible=False)
    try:
        gmsh.option.setNumber("General.Terminal", 0)
        gmsh.option.setString("Geometry.OCCTargetUnit", "M")
        gmsh.model.occ.importShapes(path)
        gmsh.model.occ.synchronize()
        return [{"body": i + 1, "volume_m3": gmsh.model.occ.getMass(*d),
                 "area_m2": sum(gmsh.model.occ.getMass(*f) for f in gmsh.model.getBoundary([d], oriented=False)),
                 "bbox_m": list(gmsh.model.occ.getBoundingBox(*d))}
                for i, d in enumerate(gmsh.model.getEntities(3))]
    finally:
        gmsh.finalize()


class InputError(Exception):
    pass


class MultiShellError(Exception):
    pass


class MeshError(Exception):
    pass


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("input")
    ap.add_argument("--out")
    ap.add_argument("--size", type=float, help="최대 요소 크기 [m]")
    ap.add_argument("--order", type=int, default=2, choices=(1, 2))
    ap.add_argument("--summary", help="요약 JSON 경로")
    ap.add_argument("--threads", type=int, default=1)
    ap.add_argument("--body", type=int, help="STEP 솔리드 번호(가져온 순서, 1부터) — 그 바디 하나만 메시")
    ap.add_argument("--list-bodies", help="메시 없이 STEP 솔리드 목록(부피·경계 상자)만 이 JSON 에 쓴다")
    a = ap.parse_args(argv)
    if a.list_bodies:
        with open(a.list_bodies, "w", encoding="utf-8") as f:
            json.dump(list_bodies(a.input), f, indent=1)
        return EXIT_OK
    if not a.out or a.size is None:
        ap.error("--out 과 --size 가 필요합니다(--list-bodies 가 아니면)")
    code, info = EXIT_OK, {}
    try:
        nodes, elems, etype, info = mesh_file(a.input, a.size, a.order, a.threads, a.body)
        write_inp(a.out, nodes, elems, etype)
        info["ok"] = True
    except InputError as ex:
        code, info = EXIT_INPUT, {"ok": False, "error": str(ex)}
    except MultiShellError as ex:
        code, info = EXIT_MULTI, {"ok": False, "error": str(ex)}
    except MeshError as ex:
        code, info = EXIT_MESH, {"ok": False, "error": str(ex)}
    if a.summary:
        with open(a.summary, "w", encoding="utf-8") as f:
            json.dump(info, f, ensure_ascii=False, indent=1)
    if code:
        print(info.get("error", ""), file=sys.stderr)
    return code


if __name__ == "__main__":
    sys.exit(main())
